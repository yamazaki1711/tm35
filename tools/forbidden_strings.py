    (r"\bbaseline_schedule\b", "имя таблицы БД baseline_schedule"),
    (r"\bcurrent_schedule\b", "имя таблицы БД current_schedule"),
    (r"\bresource_pool\b", "имя таблицы БД resource_pool"),
    (r"\baudit_log\b", "имя таблицы БД audit_log"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])work_id\b", "имя поля БД work_id"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])blocker\b", "имя таблицы БД blocker"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])location\b", "имя поля БД location"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])subcontractor\b", "имя таблицы БД subcontractor"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])material\b", "имя таблицы БД material"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])scenario\b", "имя таблицы БД scenario"),
    (r"(?<![a-zA-Zа-яА-Я0-9_])works\b", "имя таблицы БД works (или сырое множественное число)"),
    # Служебные метки парсера/разработки
    (r"\[день-уровень,?\s*Excel\]", "служебная метка парсера"),
    (r"\bдень-уровень\b", "служебная метка парсера"),
    # "WORK:" — префикс из исходного текста комментариев в Excel-файле
    # (см. skill tm35-excel), не наш, но тоже не для показа пользователю
    # как есть — найден вживую 20.08.2026 на /today, "Ограничения к
    # снятию" (blocker.description после снятия [день-уровень, Excel]).
    (r"\bWORK:", "служебная метка исходного комментария Excel"),
    # Пути к файлам репозитория/докам в пользовательском тексте — найдено
    # вживую 20.08.2026 (docs/DATA_QUALITY_REVIEW.md, docs/MATRIX_
