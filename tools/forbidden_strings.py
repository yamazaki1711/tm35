    (r"\bbackend/[a-zA-Z0-9_\-./]+\.py\b", "путь к файлу исходного кода"),
    (r"\bснимок\b", "служебный термин разработки"),
    (r"\bproxy\b", "служебный термин разработки"),
    (r"прокси", "служебный термин разработки"),
    (r"хардкод", "служебный термин разработки"),
    # Форматы дат/недель
    (r"\b\d{4}-\d{2}-\d{2}\b", "дата в формате ISO (ГГГГ-ММ-ДД)"),
    (r"\b\d{2}/\d{2}/\d{4}\b", "дата в американском формате (ММ/ДД/ГГГГ)"),
    (r"\bW\d{1,2}\b", "неделя в формате номера (W34)"),
    (r"\b\d{4}-W\d{1,2}\b", "неделя в формате ISO-номера (2026-W34)"),
    # Пустые/непереведённые значения — добавлено 29.08.2026 (сплошной аудит, цикл 1)
