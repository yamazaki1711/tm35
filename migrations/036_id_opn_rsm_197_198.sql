-- Координатор, 15.09.2026: при подготовке исходного xlsx пропущены два
-- раздела вкладки «ОПН (рсм)» (tab_id=2, code='opn_rsm') — ОПн197 и
-- ОПн198. Проверено: их нет нигде в id_form_row (искали и точное
-- совпадение, и варианты написания) — это не перенос, а вставка.
-- Найдены только похожие, но НЕ те же лейблы на другой вкладке
-- («Скользячки», tab_id=4): «Т1-Опн197»/«Т1-Опн198» и
-- «Т2-Опн197»/«Т2-Опн198» — составные метки с собственной, отдельной от
-- «ОПН (рсм)» нумерацией по трубам (Т1/Т2), номер 197/198 у неё уже
-- дважды повторяется внутри самой вкладки «Скользячки» — совпадение
-- числа, не тот же раздел, трогать не нужно.
--
-- section_label — единственное поле, где вкладка хранит видимую метку
-- («ОПн15» и т.п., см. существующие 209 строк tab_id=2) —
-- construction_label/foundation_label у всех строк этой вкладки NULL,
-- то же самое повторено здесь, не изобретается.
--
-- source_row — плотная последовательность 1..209 внутри вкладки (не
-- буквальный номер строки исходного xlsx: соседние по source_row метки
-- местами идут не по числовой линейке лейбла, напр. ОПн57 стоит перед
-- ОПн48 — так было в исходнике и раньше, эта миграция такие места не
-- трогает). Свободного номера между ОПн196 (source_row=100) и ОПн199
-- (source_row=101) нет — оба соседних. Раздвигаем ТОЛЬКО хвост этой
-- вкладки (source_row >= 101 у tab_id=2), не всю таблицу и не другие
-- вкладки, и вставляем 197/198 в освободившиеся 101/102 — так они
-- встают в матрице ровно между ОПн196 и ОПн199, как в исходной нумерации.
--
-- Никакой id_form_entry не создаётся — раздел без единой записи,
-- честная пустая ячейка в матрице до первого ввода ответственного
-- инженера.
--
-- Идемпотентно: если ОПн197 уже есть на этой вкладке, весь блок — no-op.

begin;

do $$
begin
    if not exists (
        select 1 from id_form_row where tab_id = 2 and section_label = 'ОПн197'
    ) then
        update id_form_row
           set source_row = source_row + 2
         where tab_id = 2
           and source_row >= 101;

        insert into id_form_row (tab_id, section_label, construction_label, foundation_label, source_row, note)
        values
            (2, 'ОПн197', null, null, 101,
             'Раздел отсутствовал в исходном xlsx, добавлен по указанию координатора от 15.09.2026'),
            (2, 'ОПн198', null, null, 102,
             'Раздел отсутствовал в исходном xlsx, добавлен по указанию координатора от 15.09.2026');
    end if;
end $$;

commit;
