-- Координатор, 22.10.2026: на вкладку «ОПН» (id_form_tab.id = 1, зона
-- ввода Денисова М.В.) добавляются три раздела: ОПв24.1, ОПв25, ОПв26.
--
-- Эти метки уже существуют на вкладке «Мет констр» (id 1071–1073) —
-- это норма проекта: физическая опора живёт на обеих вкладках
-- (ОПв1–ОПв24 и так присутствуют на обеих), вкладки разного назначения.
-- На вкладке ОПН дубликатов нет (проверено перед накаткой).
--
-- Соглашение ручных строк (по образцу ОПн197/198 от 15.09.2026):
-- note помечает внесение не из xlsx, source_row продолжает max(tab).
-- Откат: delete from id_form_row where id in (…id после накатки…);
-- допустимо, пока по строкам нет записей id_form_entry.

begin;

insert into id_form_row (tab_id, section_label, source_row, note)
select 1, v.label, v.sr,
       'Раздел отсутствовал в исходном xlsx, добавлен по указанию координатора от 22.10.2026'
from (values ('ОПв24.1', 164), ('ОПв25', 165), ('ОПв26', 166)) as v(label, sr)
where not exists (
    select 1 from id_form_row
    where tab_id = 1 and section_label = v.label
);

commit;
