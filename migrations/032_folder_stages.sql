-- Ночной прогон 09-10.09.2026, задача 3: «Обзор ИД» вокруг папок, не
-- разделов — единица работы и денег заказчик видит по ПОДПИСАННОЙ
-- папке, а модель до сих пор не различала "передана в СДО" и
-- "подписана" (signed_folders_sum считался по sdo_transfer_date — то
-- есть по факту "отправлено на проверку", не "принято и подписано").
--
-- Стадия папки НЕ хранится отдельным полем — вычисляется функцией
-- id_folder_stage() (main.py) по тому, какая из дат ниже заполнена
-- последней: Сформирована → Передана в СДО → Проверка → Подписана →
-- КС-2. Та же дисциплина, что и весь проект — не дублировать состояние
-- в отдельной колонке, которая может разойтись с фактом (см.
-- AUDIT_DATA_INTEGRITY_2026-09-08.md).
--
-- amount_rub — старое поле (прикидка ПТО при сборке папки) НЕ удаляется
-- и не переименовывается (правило проекта), но с этой миграции больше
-- не используется в денежных показателях — источник истины теперь
-- amount_smeta_rub, вносится по факту подписания папки.

begin;

alter table id_folder
    add column check_start_date date,
    add column signed_date date,
    add column signed_by text,
    add column ks2_date date,
    add column ks2_no text,
    add column amount_smeta_rub numeric(14,2);

comment on column id_folder.amount_rub is
    'Предварительная оценка ПТО при сборке папки (не факт) — с 09-10.09.2026 '
    '(ночной прогон, задача 3) НЕ используется в денежных показателях. '
    'Денежный источник истины — amount_smeta_rub, вносится по факту подписания.';

comment on column id_folder.amount_smeta_rub is
    'Сметная стоимость папки по факту подписания — денежный источник '
    'истины для "Сумма подписанных папок"/"Остаток в деньгах" с 09-10.09.2026. '
    'Доступно к вводу только после того, как заполнена signed_date.';

commit;
