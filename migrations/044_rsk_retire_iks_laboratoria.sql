-- Координатор, 25.09.2026 (аддендум к «один ответственный отдел») —
-- «ИКС» и «Лаборатория» убираются из контура РСК как варианты выбора
-- целиком. «ИКС» уже была неактивна (миграция 038, 16.09.2026,
-- координатор 16.09.2026) — эта миграция ничего не меняет для неё,
-- только для «Лаборатория» (была активна). Строки справочника не
-- удаляются (правило проекта: ничего не удаляем), только `active =
-- false` — тот же, уже использованный для «ИКС», механизм.
--
-- На 25.09.2026, прямой проверкой перед накаткой: ни у одного
-- нарушения `rsk_processing.responsible_id` не указывает ни на «ИКС»,
-- ни на «Лаборатория» (0 и 0 из 152) — переносить в «не назначен»
-- буквально нечего. UPDATE ниже всё равно написан безусловно (не
-- «отдельно только если найдётся»), чтобы миграция была корректна
-- независимо от того, когда её на самом деле накатывают.

begin;

update rsk_responsible set active = false where name = 'Лаборатория';

update rsk_processing set responsible_id = null
where responsible_id in (select id from rsk_responsible where name in ('ИКС', 'Лаборатория'));

commit;
