-- Ночной прогон 09-10.09.2026, задача 2: новый статус «Подписано в
-- карандаше» — требование ПТО от 09.09.2026, встаёт в цепочке ПЕРЕД
-- «Подписано» (предварительное согласование, официальной подписи нет).
-- Справочник унифицирован 03.09.2026 (17 вкладок × 9 значений,
-- display_order 1..9, «Подписано» везде на позиции 7) — держим единым,
-- вставляем на позицию 7 во всех вкладках разом, существующие 7-9
-- сдвигаем на +1.
--
-- Важно (см. main.py, status_fill_color/_status_tier/_status_is_full):
-- код 'Подписано в карандаше' НЕ равен 'Подписано' — все существующие
-- SQL-счётчики фильтруют точным совпадением s.code='Подписано', поэтому
-- новый статус нигде не засчитывается подписанным сам по себе. Ловушка
-- была только в экспорте «График ИД», где легенда красит по префиксу
-- "подписано" (ради "Подписано 80%") — там заведено явное исключение.

begin;

update id_form_status set display_order = display_order + 1 where display_order >= 7;

insert into id_form_status (tab_id, code, label, display_order, is_stopper)
select id, 'Подписано в карандаше', 'Подписано в карандаше', 7, false
from id_form_tab;

commit;
