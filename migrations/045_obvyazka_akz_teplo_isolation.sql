-- 'obvyazka', id=10) добавляются два вида работ — «АКЗ» и
-- «Тепло-изоляция» (формулировки дословно из задания). Повторение
-- миграции 045 от 17.10.2026: та была откачена 19.10.2026 в составе
-- полного отката правок 17.10, сейчас добавление подтверждено
-- отдельным заданием.
--
-- До миграции на вкладке два вида работ («Монтаж магистральных
-- трубопроводов», «Монтаж трубопроводов», display_order 1–2), новые
-- продолжают нумерацию с 3. Колонки responsible_name/signer_name —
-- легаси (каталог ответственных читается из id_form_responsible),
-- оставлены NULL. Вставка идемпотентна.
--
-- Откат: delete from id_form_work_type where tab_id = 10
--        and name in ('АКЗ', 'Тепло-изоляция');
-- (допустимо, пока по этим видам работ нет записей ввода; id после
-- накатки зафиксированы в run log).

begin;

insert into id_form_work_type (tab_id, name, display_order)
select 10, v.name, v.ord
from (values ('АКЗ', 3), ('Тепло-изоляция', 4)) as v(name, ord)
where not exists (
    select 1 from id_form_work_type
    where tab_id = 10 and name = v.name
);

commit;
