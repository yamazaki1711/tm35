-- (Сметаненко, TM35-MAIN-110/2026-09-16) — уже ПОСЛЕ того, как 040
-- считалась завершившей инцидент. Найдено новой "живой" проверкой в
-- tools/check_consistency.py (18.09.2026), которая выполняет UPDATE и
-- сверяется без опоры на права kat_admin.
--
-- Настоящая причина оказалась проще, чем предполагала миграция 040:
-- ОРИГИНАЛЬНАЯ таблица (создана 31.08.2026, принадлежит `tm35_app`,
-- 2301 реальная строка истории по 15.09.2026 включительно) никуда не
-- девалась — её увели в схему `archive` 15.09.2026 вместе с настоящими
-- одноразовыми таблицами `*_backup_*` при уборке, по совпадению схожего
-- имени (это не бэкап, это рабочая таблица, в которую пишет триггер).
-- Здесь она возвращается в `public` — вместе со всей историей — и
-- ошибочно созданный миграцией 040 дубликат (принадлежал `kat_admin`,
-- содержал только тестовые записи текущей сессии) удаляется.

begin;

do $$
begin
  if exists (
    select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'archive' and c.relname = 'daily_progress_audit_trap'
  ) then
    if exists (
      select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relname = 'daily_progress_audit_trap'
    ) then
      execute 'drop table public.daily_progress_audit_trap';
    end if;
    execute 'alter table archive.daily_progress_audit_trap set schema public';
  end if;
end
$$;

commit;

