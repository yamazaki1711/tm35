-- Координатор, 25.09.2026 — поправка к контуру РСК: у нарушения РОВНО
-- один ответственный отдел, множественный выбор не допускается.
-- rsk_processing_responsible (m2m, миграция 024_rsk_processing.sql)
-- допускала несколько отделов на одно нарушение — 24.09.2026 это было
-- реальностью для 46 из 152 нарушений (198 строк на 152 processing),
-- см. docs/RUN_20260924_rsk_overview_unify.md. К моменту этой миграции
-- (25.09.2026, живая проверка прямо перед накаткой) данные изменились
-- обычной работой ПТО — сейчас ВСЕ 152 processing-строки имеют РОВНО
-- один отдел, ни одной с нулём или больше одного. Бэкофилл ниже это не
-- предполагает, а сам заново пересчитывает по факту на момент накатки.
--
-- Старая таблица `rsk_processing_responsible` и её данные НЕ удаляются
-- и не трогаются (координатор: держать до отдельного решения) — новые
-- записи через неё больше не пишутся, форма `/rsk/processing` переведена
-- на одиночный выбор (радиокнопки) поверх нового столбца.

begin;

alter table rsk_processing add column responsible_id bigint references rsk_responsible(id);

-- Бэкофилл: ровно один отдел у processing-строки → переносится в новый
-- столбец. Ноль или больше одного (на 25.09.2026 таких нет, но правило
-- должно быть верным независимо от даты применения) — остаётся NULL,
-- ПТО назначит один отдел вручную через новую форму; такие нарушения
-- уже показываются в реестре как "без ответственного" (существующий
-- паттерн, ничего нового не вводится).
with counts as (
    select processing_id, count(*) as n, min(responsible_id) as only_id
    from rsk_processing_responsible
    group by processing_id
)
update rsk_processing p
set responsible_id = c.only_id
from counts c
where c.processing_id = p.id and c.n = 1;

commit;
