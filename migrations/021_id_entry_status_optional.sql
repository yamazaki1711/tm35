-- Подготовка пилота: 7 из 17 вкладок ИД (n, sodk, opv, izolyaciya,
-- elektrika, met_konstr, lotki) не имеют ни одного справочника
-- статусов — отправить запись было нельзя ни при каких правах.
-- Решение координатора: не подставлять заглушку, разрешить пустой
-- статус там, где справочника физически нет; на вкладках со
-- справочником статус остаётся обязательным (проверяется в коде,
-- не в БД, схема сама по себе не знает "у какой вкладки есть
-- справочник").
alter table id_form_entry alter column status_id drop not null;
