report = []
for order, (code, label, has_block, stated_rows, sts, resp, wts, old_keys) in enumerate(TABS, start=1):
    note = None if has_block else "Справочного блока на этой вкладке нет в исходнике — не подтверждено ПТО, не повреждение."
    cur.execute(
        """insert into id_form_tab (code, label, has_section_level, display_order, source_sheet, has_reference_block, note)
           values (%s,%s,%s,%s,%s,%s,%s) returning id""",
        (code, label, True, order, label, has_block, note),
    )
    tab_id = cur.fetchone()['id']

    for i, s in enumerate(sts, start=1):
        cur.execute(
            """insert into id_form_status (tab_id, code, label, display_order, is_stopper)
               values (%s,%s,%s,%s,%s) on conflict (tab_id, code) do nothing""",
            (tab_id, s, s, i, s in STOPPER_LABELS),
        )

    for i, (role, name) in enumerate(resp, start=1):
        cur.execute(
            """insert into id_form_responsible (tab_id, role, full_name, display_order)
               values (%s,%s,%s,%s)""",
            (tab_id, role, name, i),
        )

    for i, w in enumerate(wts, start=1):
        cur.execute(
            """insert into id_form_work_type (tab_id, name, display_order, responsible_name, signer_name, source_col)
               values (%s,%s,%s,NULL,NULL,NULL) on conflict (tab_id, name) do nothing""",
            (tab_id, w, i),
        )

    loaded_rows = 0
    for old_key in old_keys:
        for r in OLD_ROWS.get(old_key, []):
            cur.execute(
                """insert into id_form_row (tab_id, section_label, construction_label, foundation_label, source_row)
                   values (%s,%s,%s,%s,%s)""",
                (tab_id, r['section'], r['construction'], r['foundation'], r['source_row']),
            )
            loaded_rows += 1

    report.append((code, label, has_block, len(sts), len(resp), len(wts), loaded_rows, stated_rows))

