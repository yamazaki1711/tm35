"""
Итоговый справочник норм ГЭСН-2022 (Минстрой России) для ТМ-35 —
из gesn_norms.json. Заменяет более раннюю версию на базе ЕНиР
(1999-2000): современный официальный источник, закрывает пробелы
(монолитный жб — сборник 6, пусконаладка не покрыта вообще ни ЕНиР,
ни этим набором сборников — отдельный вопрос ГЭСНп, см. .md), даёт
97,5% автоматического покрытия против 73,1% у ЕНиР.

Один код ГЭСН = одна строка (в отличие от ЕНиР, где параметрическую
таблицу приходилось разворачивать вручную — у ГЭСН каждая комбинация
параметров уже имеет свой отдельный код изначально).
"""
import json
from collections import Counter, defaultdict

import openpyxl
from openpyxl.styles import Font, Alignment
from openpyxl.utils import get_column_letter

SRC = "/home/oleg/Documents/TM-35/import/enir_work/gesn_norms.json"
XLSX_OUT = "/home/oleg/Documents/TM-35/docs/spravochnik_GESN_TM35.xlsx"
MD_OUT = "/home/oleg/Documents/TM-35/docs/spravochnik_GESN_TM35.md"

SBORNIK_TITLES = {
    "GESN_01_Zemlyanye": "ГЭСН 81-02-01-2022 Сборник 1. Земляные работы",
    "GESN_05_Svainye": "ГЭСН 81-02-05-2022 Сборник 5. Свайные работы, опускные колодцы, закрепление грунтов",
    "GESN_06_Beton_monolit": "ГЭСН 81-02-06-2022 Сборник 6. Бетонные и железобетонные конструкции монолитные",
    "GESN_09_Metallokonstrukcii": "ГЭСН 81-02-09-2022 Сборник 9. Строительные металлические конструкции",
    "GESN_13_Korroziya": "ГЭСН 81-02-13-2022 Сборник 13. Защита строительных конструкций и оборудования от коррозии",
    "GESN_24_Teplosnabzhenie": "ГЭСН 81-02-24-2022 Сборник 24. Теплоснабжение и газопроводы - наружные сети",
    "GESN_26_Teploizolyaciya": "ГЭСН 81-02-26-2022 Сборник 26. Теплоизоляционные работы",
    "GESN_27_Dorogi": "ГЭСН 81-02-27-2022 Сборник 27. Автомобильные дороги",
    "GESN_33_LEP": "ГЭСН 81-02-33-2022 Сборник 33. Линии электропередачи",
    "GESN_47_Ozelenenie": "ГЭСН 81-02-47-2022 Сборник 47. Озеленение, защитные лесонасаждения",
    "GESNm_08_Elektrotekhn": "ГЭСНм 81-03-08-2022 Сборник 8. Электротехнические установки",
    "GESNm_12_Tekhnolog_truboprovody": "ГЭСНм 81-03-12-2022 Сборник 12. Технологические трубопроводы",
}

HEADERS = ["Сборник", "Код ГЭСН", "Наименование работы", "Ед. изм.",
           "Норма времени, чел-час (рабочие+машинисты)", "Примечание"]


def main():
    groups = json.load(open(SRC, encoding="utf-8"))

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Нормы ГЭСН"
    ws.append(HEADERS)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.alignment = Alignment(wrap_text=True, vertical="top")

    ws2 = wb.create_sheet("Не разобрано автоматически")
    ws2.append(["Сборник", "Код ГЭСН", "Наименование работы", "Ед. изм.", "Примечание"])
    for c in ws2[1]:
        c.font = Font(bold=True)

    by_sbornik_total = Counter()
    by_sbornik_ok = Counter()

    for g in groups:
        sb_title = SBORNIK_TITLES.get(g["sbornik"], g["sbornik"])
        group_title = (g.get("group_title") or "").strip()
        for c in g["codes"]:
            by_sbornik_total[sb_title] += 1
            # Название таблицы (group_title) часто несёт контекст, не
            # повторённый в имени конкретного кода (напр. давление/
            # температура теплоносителя вынесены только в заголовок
            # таблицы, а у кода остаётся лишь "диаметр труб 50 мм") —
            # склеиваем, чтобы название было понятно само по себе.
            full_name = f"{group_title}: {c['name']}" if group_title and group_title not in c["name"] else c["name"]
            if c["hours_per_unit"] is not None:
                by_sbornik_ok[sb_title] += 1
                ws.append([sb_title, c["code"], full_name, c.get("unit") or "", c["hours_per_unit"], ""])
            else:
                ws2.append([sb_title, c["code"], full_name, c.get("unit") or "",
                            "Норма не извлечена автоматически — не выдумано, см. первоисточник в gesn_pdf/."])

    for sheet, widths in ((ws, [45, 16, 55, 14, 22, 30]), (ws2, [45, 16, 55, 14, 40])):
        for i, w in enumerate(widths, 1):
            sheet.column_dimensions[get_column_letter(i)].width = w
        sheet.freeze_panes = "A2"

    wb.save(XLSX_OUT)

    total = sum(by_sbornik_total.values())
    total_ok = sum(by_sbornik_ok.values())

    md = []
    md.append("# Справочник норм ГЭСН-2022 для ТМ-35\n")
    md.append(
        "Официальные, современные (2022, Минстрой России) сметные нормы — "
        "заменяет более раннюю версию на базе ЕНиР (1999–2000, см. "
        "историю замен ниже). Источник — открытое API ФГИС ЦС "
        "(`fgiscs.minstroyrf.ru`), PDF каждого сборника сохранены в "
        "`import/enir_work/gesn_pdf/` для проверки. Разбор — "
        "`import/enir_work/parse_gesn.py`, из текста "
        "`pdftotext -layout`, числа сверены вручную построчно на "
        "нескольких сборниках разного формата таблиц.\n"
    )
    md.append("## Сводка охвата\n")
    md.append(f"- Всего кодов ГЭСН в 12 сборниках: **{total}**")
    md.append(f"- С извлечённой нормой (чел-час, рабочие+машинисты): **{total_ok}** ({100*total_ok/total:.1f}%)")
    md.append(f"- Не разобрано автоматически: **{total-total_ok}** ({100*(total-total_ok)/total:.1f}%)")
    md.append("")
    md.append(
        "**Метод трудозатрат.** Для каждого кода — сумма двух строк "
        "ресурсной таблицы: «Средний разряд работы X,Y» (рабочие) + "
        "«Затраты труда машинистов» (машинисты, если есть). Расход "
        "материалов и машино-часы механизмов в справочник не включены "
        "(не нужны для расчёта человеко-часов)."
    )
    md.append("")
    md.append("## Охват по сборникам\n")
    md.append("| Сборник | Кодов всего | С нормой | % |")
    md.append("|---|---|---|---|")
    for name in sorted(by_sbornik_total):
        t = by_sbornik_total[name]
        ok = by_sbornik_ok[name]
        md.append(f"| {name} | {t} | {ok} | {100*ok/t:.0f}% |")
    md.append("")
    md.append("## История замен\n")
    md.append(
        "1. **18.08 — join со сметой ТМ-35 через ЕНиР** (отклонено "
        "координатором: «максимально далеко от того, что просил», числа "
        "не извлекались вовсе)."
    )
    md.append(
        "2. **19.08 — прямая оцифровка ЕНиР** (`spravochnik_ENiR_TM35.xlsx`, "
        "16 сборников 1999–2000, 73,1% покрытия, параметрические таблицы "
        "развёрнуты в строки). Рабочая, но устаревшая база."
    )
    md.append(
        "3. **19.08 — этот файл, ГЭСН-2022** (по предложению координатора "
        "проверить сайт Минстроя). Современный источник, 97,5% покрытия, "
        "закрывает пробел монолитного/сборного железобетона (сборник 6 — "
        "в архиве ЕНиР такого сборника не было вообще)."
    )
    md.append("")
    md.append("## Известные пробелы (честно)\n")
    md.append(
        "- **Пусконаладочные работы (ПНР)** — отдельная линейка ГЭСНп "
        "(81-05-NN-2022, напр. Сборник 1 «Электротехнические устройства», "
        "Сборник 7 «Теплоэнергетическое оборудование») существует у "
        "Минстроя, но в этот справочник ещё не включена — не начато, "
        "отдельная задача при необходимости."
    )
    md.append(
        "- Сварочные операции не выделены отдельным сборником (в ГЭСН, в "
        "отличие от ЕНиР, они встроены внутрь профильных сборников — "
        "напр. сварка металлоконструкций внутри сборника 9, сварка "
        "стыков трубопроводов внутри сборника 24/ГЭСНм-12) — искать по "
        "названию внутри соответствующего сборника, не по отдельному "
        "разделу «сварка»."
    )
    md.append(
        "- 2,5% кодов (см. лист «Не разобрано автоматически») не дали "
        "числа — таблица не подошла под распознанный шаблон парсера, "
        "не выдумано."
    )
    md.append(
        "- **Название кода иногда неполное**, если заголовок-подсказка "
        "группы в источнике занимает больше одной строки (парсер берёт "
        "только последнюю строку заголовка перед кодом) — само число и "
        "код при этом верны, для точной формулировки сверяться с PDF в "
        "`gesn_pdf/` по номеру таблицы (напр. «Таблица ГЭСН 24-01-001»)."
    )

    with open(MD_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")

    print("xlsx:", XLSX_OUT)
    print("md:", MD_OUT)
    print(f"total={total} ok={total_ok} ({100*total_ok/total:.1f}%)")


if __name__ == "__main__":
    main()
